#!/usr/bin/env node
// Runs as the FIRST step of `npm run build` (see package.json), before
// `vite build` - Vite's own build step has no D1 binding (bindings are
// Workers/Pages-Functions-runtime-only, never available to a plain
// static-site build container), so this is the only point in the whole
// pipeline that can read platform_updates and bake the result into the
// shipped bundle as a real build-time constant. See
// PilotVersionStamp.tsx's own comment for why this replaced a live
// runtime fetch to /api/public/versions.
//
// Deliberately shells out to `wrangler d1 execute --remote` rather than
// hand-rolling a raw fetch() against Cloudflare's D1 HTTP API - reuses
// the exact same tool/auth this whole codebase's own local-D1 testing
// convention already relies on, non-interactively authenticated via a
// CLOUDFLARE_API_TOKEN env var (wrangler CLI's own documented mechanism
// for CI/build environments with no interactive OAuth session
// available) - set as a Cloudflare Pages BUILD environment variable
// (Pages project settings, NOT a Pages Function secret - a build step
// has no access to those), same account CLOUDFLARE_ACCOUNT_ID
// deploy-worker.yml's own GitHub Actions job already uses.
//
// --remote always, never --local: there is no persistent local D1
// state in Cloudflare's own ephemeral build container (or in most
// developers' machines running this fresh), so remote is the only
// database that's ever actually reachable here - this intentionally
// reads the SAME real released-version data /versions and
// /platform/dev-features already show, not a stale local copy.
import { execSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUTPUT_PATH = fileURLToPath(new URL('../src/generated/pilotVersion.ts', import.meta.url))

// Mirrors functions/api/_utils/versionSort.ts exactly (not imported
// directly - that file lives in functions/, a separate Pages-Functions
// build target from this plain Node build script; see
// PlatformDevFeaturesPage.tsx's own comment on why a small duplicated
// copy is this codebase's own established convention across that
// boundary rather than crossing it). version is free-text typed into
// the release form, so 'v1.10.0' < 'v1.2.0' lexicographically - numeric,
// segment-by-segment comparison is required, not a plain string sort.
function parseVersionSegments(version) {
  return version
    .replace(/^v/i, '')
    .split('.')
    .map((segment) => {
      const n = parseInt(segment, 10)
      return Number.isFinite(n) ? n : 0
    })
}

function compareVersionsDesc(a, b) {
  const segmentsA = parseVersionSegments(a)
  const segmentsB = parseVersionSegments(b)
  const length = Math.max(segmentsA.length, segmentsB.length)
  for (let i = 0; i < length; i++) {
    const diff = (segmentsB[i] ?? 0) - (segmentsA[i] ?? 0)
    if (diff !== 0) return diff
  }
  return 0
}

function writeGeneratedFile(label) {
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true })
  writeFileSync(
    OUTPUT_PATH,
    `// AUTO-GENERATED by scripts/generate-pilot-version.mjs at build time.
// Do not edit by hand - regenerated on every \`npm run build\` from
// platform_updates (D1), the same source /api/public/versions and
// /versions themselves read from. See PilotVersionStamp.tsx's own
// comment for the full reasoning.
export const PILOT_VERSION_LABEL = ${JSON.stringify(label)}
`
  )
}

function buildLabel(version) {
  // version is free-text typed into the release form (see
  // versionSort.ts's own comment) - could already start with a 'v'/'V'.
  // Stripped before applying this label's own fixed "V" prefix so a
  // "v1.12.0" release can never render as "Vv1.12.0".
  return `AIRFIELD CENTRAL V${version.replace(/^v/i, '')}`
}

try {
  const output = execSync(
    `npx wrangler d1 execute shobdon-central --remote --json --command "SELECT version FROM platform_updates WHERE status='released' AND version IS NOT NULL"`,
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }
  )
  const parsed = JSON.parse(output)
  const rows = parsed?.[0]?.results ?? []
  const versions = rows.map((row) => row.version).filter((v) => typeof v === 'string' && v.trim())
  if (versions.length === 0) throw new Error('No released versions found in platform_updates')

  const latest = [...versions].sort(compareVersionsDesc)[0]
  const label = buildLabel(latest)
  writeGeneratedFile(label)
  console.log(`[generate-pilot-version] Wrote "${label}" (from ${versions.length} released version(s))`)
} catch (err) {
  // A failed version-stamp refresh must never fail the whole site's
  // build - the rest of /pilot (and every other route) has nothing to
  // do with this constant. If a previously-generated/committed file
  // already exists, preserve it as the last-known-good version instead
  // of replacing it with an obviously broken placeholder like "0.0.0".
  // Only a fresh clone with no prior generated file at all can fall back
  // to a placeholder, which must still be obvious in build logs.
  console.error(`[generate-pilot-version] Failed to read latest version from D1: ${err.stack ?? err.message}`)
  if (existsSync(OUTPUT_PATH)) {
    console.error('[generate-pilot-version] Keeping existing generated file as the last-known-good version.')
  } else {
    console.error('[generate-pilot-version] No existing generated file found. Writing a placeholder so the build can proceed.')
    writeGeneratedFile('AIRFIELD CENTRAL V0.0.0')
  }
}
